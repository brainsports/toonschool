// 창작 설정(분야/세부설정/주인공/배경/분위기/결말). 주제·키워드·대본·표지 생성에 전달.
// 문자열 하나로 합치지 않고 구조화된 형태로 저장/전달한다.
export interface CreativeStorySettings {
  categoryId: string;
  categoryName: string;
  genreName: string;       // 필수
  materialName: string;    // 필수
  protagonistName?: string;
  protagonistCustomText?: string;  // 주인공 '직접 입력' 시
  backgroundName?: string;
  backgroundCustomText?: string;   // 배경 '직접 입력' 시
  moodId?: string;
  moodName?: string;
  endingId?: string;
  endingName?: string;
  createdAt?: string;
}

// 요약 카드/프롬프트에 쓸 (label, value) 쌍.
export const summarizeCreativeSettings = (s: CreativeStorySettings): { label: string; value: string }[] => {
  const rows: { label: string; value: string }[] = [
    { label: '분야', value: s.categoryName },
    { label: '종류', value: s.genreName },
    { label: '소재', value: s.materialName },
  ];
  if (s.protagonistName) rows.push({ label: '주인공', value: s.protagonistCustomText || s.protagonistName });
  if (s.backgroundName) rows.push({ label: '배경', value: s.backgroundCustomText || s.backgroundName });
  if (s.moodName) rows.push({ label: '분위기', value: s.moodName });
  if (s.endingName) rows.push({ label: '결말', value: s.endingName });
  return rows;
};

